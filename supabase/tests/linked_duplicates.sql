begin;
set local statement_timeout='30s';
update public.analytics_settings set include_samples=false;
do $tests$
declare
  owner_id uuid:=gen_random_uuid(); main_owner uuid:=gen_random_uuid(); reviewer uuid:=gen_random_uuid(); outsider uuid:=gen_random_uuid(); admin_id uuid:=gen_random_uuid();
  main_id uuid:=gen_random_uuid(); child_id uuid:=gen_random_uuid(); unlinked_id uuid:=gen_random_uuid(); area uuid; other_area uuid; category uuid; problem text;
  office_id uuid:=gen_random_uuid(); payload jsonb; denied boolean; actor uuid; n integer;
begin
  select id into area from public.barangays where name='Poblacion';
  select id into other_area from public.barangays where id<>area limit 1;
  select c.id,p.code into category,problem from public.report_categories c join public.report_problem_types p on p.category_id=c.id where c.active and p.code<>'other' order by c.name,p.sort_order limit 1;
  insert into auth.users(id,email) select id,id::text||'@example.invalid' from unnest(array[owner_id,main_owner,reviewer,outsider,admin_id]) u(id);
  update public.profiles set barangay_id=area where id in(owner_id,main_owner,reviewer);
  update public.profiles set role='barangay' where id=reviewer;
  update public.profiles set role='barangay',barangay_id=other_area where id=outsider;
  update public.profiles set role='admin' where id=admin_id;
  insert into public.organizations(id,name) values(office_id,'Rollback linked report office');
  insert into public.organization_access_rules(organization_id,category_id,enabled) values(office_id,category,true);
  perform set_config('request.jwt.claim.sub',main_owner::text,true);
  set local role authenticated;
  perform public.submit_report(main_id,category,area,'Private original concern','A private original description that must not leak to another reporter.',8.22947578,124.23688253,'Private residential landmark',problem);
  reset role;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  set local role authenticated;
  perform public.submit_report(child_id,category,area,'Linked report concern','Another submission about the same physical issue for rollback tests.',8.22947578,124.23688253,'',problem);
  perform public.submit_report(unlinked_id,category,area,'Unlinked report concern','A separate record that should never receive linked main report updates.',8.22947578,124.23688253,'',problem);
  reset role;
  perform set_config('request.jwt.claim.sub',reviewer::text,true);
  set local role authenticated;
  perform public.change_report(child_id,'duplicate','Reviewed both records; they describe the same physical concern.',null,null,main_id);
  payload:=public.report_linked_duplicates(main_id);
  assert (payload->>'total_count')::integer=1,'Main report child count missing';
  assert payload->'items'->0->>'id'=child_id::text,'Linked child missing';
  assert jsonb_array_length(public.report_linked_duplicates(main_id,20)->'items')=0,'Child page is not bounded';
  denied:=false;begin perform public.report_linked_duplicates(main_id,-1);exception when invalid_parameter_value then denied:=true;end;
  assert denied,'Negative child offset accepted';
  perform public.change_report(main_id,'under_review','Checking the main report details.');
  perform public.change_report(main_id,'verified','Main report verified after review.',null,2,p_urgency=>2);
  perform public.change_report(main_id,'assigned','Forwarding the main report for maintenance.',office_id);
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  perform public.change_report(main_id,'scheduled','Maintenance work has been scheduled.',p_scheduled_at=>now()+interval '1 day');
  reset role;
  update public.reports set scheduled_at=((timezone('Asia/Manila',now())::date - 1)::timestamp at time zone 'Asia/Manila') where id=main_id;
  set local role authenticated;
  perform public.change_report(main_id,'in_progress','Work started on the main report.');
  reset role;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  set local role authenticated;
  payload:=public.report_duplicate_progress(child_id);
  assert payload->>'status'='in_progress','Linked progress did not follow main status';
  assert payload->>'organization_name'='Rollback linked report office','Linked office did not follow main';
  assert payload->>'main_title' is null and not (payload->>'can_open_main')::boolean,'Private main title leaked';
  assert not exists(select 1 from public.reports where id=main_id),'Main private row became directly readable';
  assert not exists(select 1 from jsonb_array_elements(payload->'history') h where h?'public_note' or h?'actor_id'),'Main notes or actors leaked';
  assert position('private residential' in lower(payload::text))=0,'Main location leaked';
  assert (select status='duplicate' from public.reports where id=child_id),'Child classification was overwritten';
  assert public.report_duplicate_progress(unlinked_id) is null,'Unlinked source returned main progress';
  assert exists(select 1 from public.notifications where user_id=owner_id and report_id=child_id and title='The main report linked to your submission has an update'),'Linked owner not notified';
  denied:=false;begin perform public.report_linked_duplicates(main_id);exception when insufficient_privilege then denied:=true;end;
  assert denied,'Resident could list other duplicate submissions';
  reset role;
  foreach actor in array array[outsider,main_owner] loop
    perform set_config('request.jwt.claim.sub',actor::text,true);set local role authenticated;
    denied:=false;begin perform public.report_duplicate_progress(child_id);exception when insufficient_privilege then denied:=true;end;
    assert denied,'Unrelated caller obtained linked child progress';reset role;
  end loop;
  perform set_config('request.jwt.claim.sub',reviewer::text,true);set local role authenticated;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  perform public.change_report(main_id,'resolved','The main concern is resolved.');reset role;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);set local role authenticated;
  assert public.report_duplicate_progress(child_id)->>'status'='resolved','Resolution did not propagate to displayed progress';reset role;
  update public.profiles set account_status='disabled' where id=owner_id;
  set local role authenticated;denied:=false;begin perform public.report_duplicate_progress(child_id);exception when insufficient_privilege then denied:=true;end;
  assert denied,'Disabled owner obtained linked progress';reset role;
  update public.profiles set account_status='active' where id=owner_id;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  update public.reports set is_demo=true where id in(main_id,child_id);
  perform set_config('request.jwt.claim.sub',owner_id::text,true);set local role authenticated;
  denied:=false;begin perform public.report_duplicate_progress(child_id);exception when insufficient_privilege then denied:=true;end;
  assert denied,'Hidden prepared links leaked';reset role;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);update public.analytics_settings set include_samples=true;
  set local role authenticated;assert public.report_duplicate_progress(child_id)->>'status'='resolved','Visible prepared links unavailable';reset role;
  set local role anon;denied:=false;begin perform public.report_duplicate_progress(child_id);exception when insufficient_privilege then denied:=true;end;
  assert denied,'Anonymous progress exposed';reset role;
  perform set_config('request.jwt.claim.sub',owner_id::text,true);
  alter table public.reports disable trigger report_rate;
  for n in 1..22 loop
    unlinked_id:=gen_random_uuid();
    insert into public.reports(id,resident_id,category_id,problem_type,barangay_id,title,description,latitude,longitude,status,is_demo)
    values(unlinked_id,owner_id,category,problem,area,'Pagination linked record '||n,'A rollback-only duplicate submission for testing bounded linked record pages.',8.22947578,124.23688253,'duplicate',true);
    insert into public.report_duplicate_links(report_id,canonical_id,reason) values(unlinked_id,main_id,'Rollback-only duplicate page fixture.');
  end loop;
  perform set_config('request.jwt.claim.sub',admin_id::text,true);set local role authenticated;
  payload:=public.report_linked_duplicates(main_id);
  assert (payload->>'total_count')::integer=23 and jsonb_array_length(payload->'items')=20,'Linked children first page is not bounded';
  assert jsonb_array_length(public.report_linked_duplicates(main_id,20)->'items')=3,'Second linked child page is incorrect';reset role;
end $tests$;
rollback;
select 'PASS: linked reports, scoped children, live main progress, private projection and notifications; all fixtures rolled back' as result;
